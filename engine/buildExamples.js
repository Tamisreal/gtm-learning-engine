// Regenerates skills/<name>/example.md from real runs of the engine.
// Usage: node engine/buildExamples.js   (Playwright optional: adds PNG screenshots)
const { execFileSync } = require("child_process");
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
// Outputs print local absolute paths; make them repo-relative before committing.
const run = (...args) => execFileSync("node", args, { cwd: ROOT, encoding: "utf8" }).trim().split(ROOT + path.sep).join("").replace(/\\/g, "/");
const section = (md, start, end) => {
  const i = md.indexOf(start);
  const j = end ? md.indexOf(end, i + start.length) : -1;
  return md.slice(i, j > -1 ? j : undefined).trim();
};
const write = (skill, title, body) => {
  const dir = path.join(ROOT, "skills", skill);
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(
    path.join(dir, "example.md"),
    `# Example: ${title}\n\n_Generated by \`node engine/buildExamples.js\` from synthetic data. No real companies or people._\n\n${body}\n`
  );
};
const code = (s) => "```\n" + s + "\n```";

async function main() {
  for (const s of ["prospect-landing-page", "proof-screenshot"]) fs.mkdirSync(path.join(ROOT, "skills", s), { recursive: true });
  run("engine/learning/state.js", "--reset");
  run("engine/simulate.js", "--save");
  run("engine/run.js");
  const report = fs.readFileSync(path.join(ROOT, "out", "report.md"), "utf8");
  const accounts = require("../data/accounts.json");

  write("account-research", "a rep asks about an account in Slack", "**Rep types:** `/gtm research Granite Payments`\n\n**Bot replies:**\n\n" + code(run("engine/slack/server.js", "research", "Granite", "Payments")));

  write(
    "bounce-check",
    "a rep flags a bad email in Slack",
    "**Case 1: the contact left the company**\n\n`/gtm bounce taylor.silva@granitepayments.example`\n\n" +
      code(run("engine/slack/server.js", "bounce", "taylor.silva@granitepayments.example")) +
      "\n\n**Case 2: still there, email is bad, waterfall finds a new one**\n\n`/gtm bounce quinn.rossi@granitesystems.example`\n\n" +
      code(run("engine/slack/server.js", "bounce", "quinn.rossi@granitesystems.example"))
  );

  const { detectSignals } = require("./signals/detect");
  const scan = accounts
    .slice(0, 6)
    .map((a) => `${a.name} (${a.domain})\n` + (detectSignals(a).map((s) => `  - ${s.label}   [${s.evidence}]`).join("\n") || "  - no signals"))
    .join("\n\n");
  write(
    "competitor-scan",
    "scanning a territory's websites for competitor code",
    "**Run:** `node engine/signals/scanSites.js` (offline on seed data) or `--live domains.txt` against real sites.\n\n" +
      code(run("engine/signals/scanSites.js")) +
      "\n\n**Signals per account, as the rest of the engine sees them:**\n\n" +
      code(scan)
  );

  const tofu = section(report, "| Tier | Account", "\n\nLanding pages").split("\n").slice(0, 8).join("\n");
  const sf = JSON.parse(fs.readFileSync(path.join(ROOT, "out", "crm_salesforce.json"), "utf8")).find((r) => r.objectType === "Account");
  write("personalized-messaging", "angle and opening line per account, written to CRM", "**Top of the ranked list:**\n\n" + tofu + "\n\n**What lands on the Salesforce Account (SDRs use it as a merge field):**\n\n```json\n" + JSON.stringify(sf, null, 2) + "\n```");

  write("precall-brief", "brief for a Tier A account", "### " + section(report, "## MOFU", "## BOFU").split("\n## ")[1]);

  write("call-analysis", "one discovery call", "**Input:** [data/transcripts/call-001.txt](../../data/transcripts/call-001.txt)\n\n**Output, written to the Opportunity:**\n\n" + section(report, "### call-001", "### call-002"));

  // Landing page + proof screenshot (PNG only if Playwright is installed)
  const firstPage = fs.readdirSync(path.join(ROOT, "out", "pages"))[0];
  const pageHtml = path.join(ROOT, "out", "pages", firstPage);
  fs.copyFileSync(pageHtml, path.join(ROOT, "skills", "prospect-landing-page", "example.html"));
  let shot = false;
  try {
    const { chromium } = require("playwright");
    const b = await chromium.launch();
    const p = await b.newPage({ viewport: { width: 900, height: 400 } });
    await p.goto("file://" + pageHtml);
    await p.screenshot({ path: path.join(ROOT, "skills", "prospect-landing-page", "example.png"), fullPage: true });
    await b.close();
    shot = true;
  } catch {}
  write("prospect-landing-page", "one prospect's page", (shot ? "![landing page](example.png)\n\n" : "") + "Full HTML: [example.html](example.html). One page per Tier A and B account, headline matched to the email's angle.");

  const proofOut = run("engine/proof/snapshot.js", "data centers", "ACC-001");
  const proofDir = path.join(ROOT, "out", "proof");
  if (fs.existsSync(path.join(proofDir, "ACC-001.png"))) fs.copyFileSync(path.join(proofDir, "ACC-001.png"), path.join(ROOT, "skills", "proof-screenshot", "example.png"));
  const email = JSON.parse(fs.readFileSync(path.join(proofDir, "ACC-001.email.json"), "utf8"));
  write(
    "proof-screenshot",
    '"data centers" for one prospect',
    code(proofOut) + (fs.existsSync(path.join(ROOT, "skills", "proof-screenshot", "example.png")) ? "\n\n**Screenshot embedded in the email:**\n\n![proof](example.png)" : "") + `\n\n**Email:**\n\nSubject: ${email.subject}\n\n` + email.html.replace(/<img[^>]*>/, "[screenshot]").replace(/<\/?p>/g, "").replace(/<\/?b>/g, "**")
  );

  write("message-experiment", "a test that needed an extension to call", code(run("engine/experiments/abTest.js", "4")));
  write("content-engine", "eight publishing cycles", code(run("engine/marketing/run.js", "--cycles", "8")));
  write("competitor-monitor", "one scan and approval", code(run("engine/marketing/monitor.js")) + "\n\n" + code("$ node engine/marketing/monitor.js approve Q-C8\n" + run("engine/marketing/monitor.js", "approve", "Q-C8")));
  write("search-demand", "a Search Console export", code(run("engine/marketing/searchDemand.js")));
  write("learning-loop", "ten cycles against a static playbook", code(run("engine/simulate.js")));
  console.log("Examples written to skills/*/example.md");
}

main();
